export function ndbiColor(delta) {
  if (delta >= 0.3) return '#c0392b';
  if (delta >= 0.2) return '#e67e22';
  if (delta >= 0.1) return '#f1c40f';
  if (delta > 0) return '#f9e79f';
  return '#ecf0f1';
}

