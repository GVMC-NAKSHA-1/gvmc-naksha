import dayjs from 'dayjs';
import relativeTime from 'dayjs/plugin/relativeTime';

dayjs.extend(relativeTime);

export { dayjs };

export const fmtDateTime = (d) => (d ? dayjs(d).format('DD MMM YYYY HH:mm') : '—');
export const fmtDate = (d) => (d ? dayjs(d).format('DD MMM YYYY') : '—');
export const fmtRelative = (d) => (d ? dayjs(d).fromNow() : '');
export const fmtNum = (n, digits) => (n == null || Number.isNaN(Number(n))
  ? '—'
  : Number(n).toLocaleString(undefined, digits != null ? { maximumFractionDigits: digits, minimumFractionDigits: digits } : undefined));
export const fmtPct = (v01) => (v01 == null ? '—' : `${Math.round(Number(v01) * 100)}%`);
export const humanize = (s) => String(s ?? '').replace(/_/g, ' ');

